"""
RagVault Metrics Module
Prometheus-ready metrics instrumentation
"""

import time
from functools import wraps
from typing import Callable, Optional
from prometheus_client import Counter, Histogram, Gauge, generate_latest, CONTENT_TYPE_LATEST

# ============================================================================
# COUNTERS
# ============================================================================

REQUEST_COUNT = Counter(
    'ragvault_requests_total',
    'Total number of requests',
    ['endpoint', 'method', 'status']
)

ERROR_COUNT = Counter(
    'ragvault_errors_total',
    'Total number of errors',
    ['endpoint', 'error_type']
)

QUERIES_TOTAL = Counter(
    'ragvault_queries_total',
    'Total number of queries',
    ['role', 'status']
)

TOKENS_GENERATED = Counter(
    'ragvault_tokens_generated_total',
    'Total tokens generated by LLM',
    []
)

# ============================================================================
# HISTOGRAMS
# ============================================================================

REQUEST_LATENCY = Histogram(
    'ragvault_request_latency_seconds',
    'Request latency in seconds',
    ['endpoint', 'method'],
    buckets=[0.01, 0.05, 0.1, 0.25, 0.5, 1.0, 2.5, 5.0, 10.0]
)

RETRIEVAL_LATENCY = Histogram(
    'ragvault_retrieval_latency_seconds',
    'Document retrieval latency in seconds',
    [],
    buckets=[0.01, 0.05, 0.1, 0.25, 0.5, 1.0, 2.5, 5.0]
)

RERANK_LATENCY = Histogram(
    'ragvault_rerank_latency_seconds',
    'Reranking latency in seconds',
    [],
    buckets=[0.1, 0.25, 0.5, 1.0, 2.5, 5.0, 10.0]
)

LLM_LATENCY = Histogram(
    'ragvault_llm_latency_seconds',
    'LLM response generation latency in seconds',
    [],
    buckets=[0.5, 1.0, 2.5, 5.0, 10.0, 30.0, 60.0]
)

INDEX_BUILD_DURATION = Histogram(
    'ragvault_index_build_duration_seconds',
    'Index build/refresh duration in seconds',
    [],
    buckets=[1.0, 5.0, 10.0, 30.0, 60.0, 120.0, 300.0]
)

# ============================================================================
# GAUGES
# ============================================================================

DOCUMENTS_TOTAL = Gauge(
    'ragvault_documents_total',
    'Total number of documents in the system'
)

CHUNKS_TOTAL = Gauge(
    'ragvault_chunks_total',
    'Total number of chunks indexed'
)

# ============================================================================
# HELPER FUNCTIONS
# ============================================================================

def get_metrics() -> bytes:
    """Generate Prometheus metrics output"""
    return generate_latest()


def get_metrics_content_type() -> str:
    """Get content type for metrics response"""
    return CONTENT_TYPE_LATEST


class MetricsTimer:
    """Context manager for timing operations"""
    
    def __init__(self, histogram: Histogram, labels: Optional[dict] = None):
        self.histogram = histogram
        self.labels = labels or {}
        self.start_time = None
    
    def __enter__(self):
        self.start_time = time.time()
        return self
    
    def __exit__(self, exc_type, exc_val, exc_tb):
        duration = time.time() - self.start_time
        if self.labels:
            self.histogram.labels(**self.labels).observe(duration)
        else:
            self.histogram.observe(duration)


def record_request(endpoint: str, method: str, status: str):
    """Record a request"""
    REQUEST_COUNT.labels(endpoint=endpoint, method=method, status=status).inc()


def record_error(endpoint: str, error_type: str):
    """Record an error"""
    ERROR_COUNT.labels(endpoint=endpoint, error_type=error_type).inc()


def record_query(role: str, status: str):
    """Record a query"""
    QUERIES_TOTAL.labels(role=role, status=status).inc()


def record_tokens(count: int):
    """Record tokens generated"""
    TOKENS_GENERATED.inc(count)


def update_document_count(count: int):
    """Update document gauge"""
    DOCUMENTS_TOTAL.set(count)


def update_chunk_count(count: int):
    """Update chunk gauge"""
    CHUNKS_TOTAL.set(count)


def time_retrieval():
    """Timer context for retrieval"""
    return MetricsTimer(RETRIEVAL_LATENCY)


def time_rerank():
    """Timer context for reranking"""
    return MetricsTimer(RERANK_LATENCY)


def time_llm():
    """Timer context for LLM"""
    return MetricsTimer(LLM_LATENCY)


def time_index_build():
    """Timer context for index building"""
    return MetricsTimer(INDEX_BUILD_DURATION)


def time_request(endpoint: str, method: str):
    """Timer context for requests"""
    return MetricsTimer(REQUEST_LATENCY, {'endpoint': endpoint, 'method': method})
